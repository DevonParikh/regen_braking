"""
export_for_simulink.py - give Simulink EXACTLY the same car and the same driving scenarios
as the VPython model (Milestone 4). Run from the repo root:

    python simulink/export_for_simulink.py

Writes (into simulink/):
    params_regen.m              every car + scenario parameter as MATLAB variables
    drive_cycle_straight.csv    t (s), v_ref (m/s), a_cmd (m/s^2), x (m)
    drive_cycle_corner.csv      t, v_ref, a_cmd, x, z (m), curvature (1/m)

In MATLAB:  run('params_regen.m');  then see load_drive_cycles.m and README_simulink.md.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import regen_core as rc  # noqa: E402


def _num(v):
    return repr(float(v))


def write_params(path):
    car = rc.Car()
    st = rc.make_straight_scenario()
    co = rc.make_corner_scenario()
    lines = [
        "% params_regen.m - AUTO-GENERATED by simulink/export_for_simulink.py from regen_core.py.",
        "% Do not edit by hand: change regen_core.Car and re-run the exporter, so both models",
        "% always use identical numbers. SI units throughout.",
        "",
        "%% Vehicle body",
        "veh.m      = %s;   %% kg, mass with driver" % _num(car.m),
        "veh.L      = %s;   %% m, wheelbase" % _num(car.L),
        "veh.lf     = %s;   %% m, CG to front axle  (regen_core: car.a)" % _num(car.a),
        "veh.lr     = %s;   %% m, CG to rear axle   (regen_core: car.b)" % _num(car.b),
        "veh.h      = %s;   %% m, CG height" % _num(car.h),
        "veh.track  = %s;   %% m, track width" % _num(car.track),
        "veh.Cd     = %s;   %% drag coefficient" % _num(car.Cd),
        "veh.A      = %s;   %% m^2, frontal area" % _num(car.A),
        "veh.Crr    = %s;   %% rolling resistance coefficient" % _num(car.Crr),
        "veh.mu     = %s;   %% road friction coefficient (dry)" % _num(car.mu),
        "env.g      = %s;   %% m/s^2" % _num(rc.g),
        "env.rho    = %s;   %% kg/m^3" % _num(rc.rho_air),
        "",
        "%% Motor / driveline",
        "mot.r_w    = %s;   %% m, tire radius" % _num(car.r_w),
        "mot.G      = %s;   %% gear ratio motor:wheel" % _num(car.G),
        "mot.T_max  = %s;   %% N*m, max regen torque" % _num(car.T_motor_max),
        "mot.P_max  = %s;   %% W, max mechanical regen power" % _num(car.P_motor_max),
        "mot.eta    = %s;   %% motor+inverter efficiency (mech -> elec)" % _num(car.eta_motor),
        "mot.v_fade = %s;   %% m/s, regen fades linearly to 0 below this speed" % _num(car.v_fade),
        "mot.axle   = '%s'; %% regen axle" % car.regen_axle,
        "",
        "%% Battery",
        "bat.E      = %s;   %% J (75 kWh)" % _num(car.E_batt),
        "bat.Q_Ah   = %s;   %% Ah if modeled at 350 V nominal (for battery blocks)" % _num(car.E_batt / 3600 / 350),
        "bat.SOC0   = %s;" % _num(car.SOC0),
        "bat.P_max  = %s;   %% W, max charge power below SOC_taper" % _num(car.P_batt_max),
        "bat.SOC_taper = %s; %% charge power tapers linearly to 0 between here and 100%%" % _num(car.SOC_taper),
        "bat.eta    = %s;   %% charging efficiency (elec -> chemical)" % _num(car.eta_batt),
        "",
        "%% Brake blending used by the VPython optimal strategy",
        "ctl.grip_margin = %s; %% regen axle uses at most this fraction of mu*N" % _num(rc.GRIP_MARGIN),
        "",
        "%% Scenario 1: straight-line stop",
        "sc1.v0 = %s; sc1.a_brake = %s; sc1.v_stop = %s;" % (_num(st.v0), _num(st.a_brake), _num(st.v_stop)),
        "",
        "%% Scenario 2: 90 degree corner",
        "sc2.v0 = %s; sc2.a_brake = %s; sc2.v_end = %s; sc2.R = %s;" % (
            _num(co.v0), _num(co.a_brake), _num(co.v_end), _num(co.R)),
        "sc2.approach = %s; sc2.s_brake_start = %s; sc2.exit_length = %s;" % (
            _num(co.approach), _num(co.s_brake_start), _num(co.exit_length)),
        "",
        "%% VPython headline results to compare against (kJ)",
    ]
    for name, mk in [("straight", rc.make_straight_scenario), ("corner", rc.make_corner_scenario)]:
        r = rc.simulate(car, mk(), rc.optimal_strategy())
        lines.append("vp.%s.E_stored_kJ = %s; vp.%s.E_fric_kJ = %s; vp.%s.regen_share = %s;" % (
            name, _num(r.E_stored / 1e3), name, _num(r.E_fric / 1e3), name, _num(r.regen_share())))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


def write_drive_cycle(path, kind):
    car = rc.Car()
    sc = rc.make_straight_scenario() if kind == "straight" else rc.make_corner_scenario()
    r = rc.simulate(car, sc, rc.optimal_strategy())
    rows = rc.timeseries_rows(r)
    cols = ["t", "v_ref", "a_cmd", "x"] + (["z", "curvature"] if kind == "corner" else [])
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        w.writerow([0.0, sc.v0, 0.0, -sc.approach if kind == "corner" else 0.0] +
                   ([0.0, 0.0] if kind == "corner" else []))
        for i in range(4, len(rows), 5):          # every 0.1 s
            q = rows[i]
            out = [round(q["t"], 4), round(q["speed"], 5), q["a_cmd"], round(q["x"], 4)]
            if kind == "corner":
                curv = 1.0 / sc.R if q["F_lat"] > 0 else 0.0
                out += [round(q["z"], 4), curv]
            w.writerow(out)
    return path


if __name__ == "__main__":
    print(write_params(os.path.join(HERE, "params_regen.m")))
    print(write_drive_cycle(os.path.join(HERE, "drive_cycle_straight.csv"), "straight"))
    print(write_drive_cycle(os.path.join(HERE, "drive_cycle_corner.csv"), "corner"))
